-- Presenter slots are stable ordered records owned by Session Events.
create table public.presentation_slots (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete restrict,
  position integer not null check (position > 0),
  officer_id bigint references public.officers(id) on delete restrict,
  presentation_title text check (presentation_title is null or length(pg_catalog.btrim(presentation_title)) between 1 and 200),
  resource_url text check (resource_url is null or resource_url ~* '^https?://[^[:space:]]+$'),
  difficulty text check (difficulty is null or length(difficulty) <= 100),
  prep_notes text check (prep_notes is null or length(pg_catalog.btrim(prep_notes)) between 1 and 2000),
  created_at timestamptz not null default pg_catalog.now(),
  constraint presentation_slots_event_position_key unique (event_id, position)
    deferrable initially deferred,
  constraint presentation_slots_presenter_signup_fkey foreign key (event_id, officer_id)
    references public.event_officers(event_id, officer_id) on delete restrict
);
create index presentation_slots_officer_id_idx on public.presentation_slots(officer_id) where officer_id is not null;

alter table public.presentation_slots enable row level security;
revoke all on public.presentation_slots from public, anon, authenticated;
grant select on public.presentation_slots to authenticated;
create policy "Approved officers read presenter slots" on public.presentation_slots
  for select to authenticated using ((select private.current_active_officer_id()) is not null);

create function private.is_session_event_type(p_event_type_id bigint) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.event_types t where t.id=p_event_type_id
    and pg_catalog.lower(pg_catalog.btrim(t.name))='session')
$$;
revoke all on function private.is_session_event_type(bigint) from public, anon, authenticated;

create function private.assert_session_presenter_slots() returns trigger
language plpgsql set search_path = '' as $$
begin
  if not private.is_session_event_type((select event_type_id from public.events where id=new.event_id)) then
    raise exception 'Presenter slots are only allowed for Session Events';
  end if;
  return new;
end;
$$;
revoke all on function private.assert_session_presenter_slots() from public, anon, authenticated;
create trigger presentation_slots_session_only before insert or update of event_id
  on public.presentation_slots for each row execute function private.assert_session_presenter_slots();

-- Guard every Event update path, including normal edits and recurring mutations.
create function private.prevent_event_type_change_with_presenter_slots() returns trigger
language plpgsql set search_path = '' as $$
begin
  if old.event_type_id is distinct from new.event_type_id
    and exists(select 1 from public.presentation_slots s where s.event_id=old.id)
    and not private.is_session_event_type(new.event_type_id) then
    raise exception 'Remove presenter slots before changing this Event from Session type';
  end if;
  return new;
end;
$$;
revoke all on function private.prevent_event_type_change_with_presenter_slots() from public, anon, authenticated;
create trigger events_keep_presenter_slots_session_only before update of event_type_id on public.events
  for each row execute function private.prevent_event_type_change_with_presenter_slots();

create function private.prevent_session_type_rename_with_slots() returns trigger
language plpgsql set search_path = '' as $$
begin
  if pg_catalog.lower(pg_catalog.btrim(old.name))='session'
    and pg_catalog.lower(pg_catalog.btrim(new.name))<>'session'
    and exists(select 1 from public.events e join public.presentation_slots s on s.event_id=e.id
      where e.event_type_id=old.id) then
    raise exception 'Cannot rename the Session Event Type while presenter slots exist';
  end if;
  return new;
end;
$$;
revoke all on function private.prevent_session_type_rename_with_slots() from public,anon,authenticated;
create trigger event_types_keep_session_identity before update of name on public.event_types
  for each row execute function private.prevent_session_type_rename_with_slots();

create function private.presenter_slots_open(p_event public.events) returns boolean
language sql stable set search_path = '' as $$
  select p_event.deleted_at is null and p_event.status <> 'cancelled'
    and p_event.participation_points_per_hour_at_end is null and p_event.starts_at > pg_catalog.now()
$$;
revoke all on function private.presenter_slots_open(public.events) from public, anon, authenticated;

create function private.audit_presentation_slot_holder() returns trigger
language plpgsql security definer set search_path = '' as $$
declare actor_id bigint := private.current_active_officer_id();
begin
  if old.officer_id is not null then
    perform private.write_audit_log(case when old.officer_id=actor_id then 'presentation.released' else 'presentation.unassigned' end,
      'event',old.event_id::text,pg_catalog.jsonb_build_object('slot_id',old.id,'position',old.position,
        'difficulty',old.difficulty,'officer_id',old.officer_id,'actor_id',actor_id,'reason',
        case when nullif(pg_catalog.current_setting('cappy.presentation_release_reason',true),'')='signup_removed'
          then 'signup_removed' when not exists(select 1 from public.officers where id=old.officer_id and status='active')
          then 'officer_deactivated' else 'requested' end));
  end if;
  if new.officer_id is not null then
    perform private.write_audit_log(case when new.officer_id=actor_id then 'presentation.claimed' else 'presentation.assigned' end,
      'event',new.event_id::text,pg_catalog.jsonb_build_object('slot_id',new.id,'position',new.position,
        'difficulty',new.difficulty,'officer_id',new.officer_id,'actor_id',actor_id));
  end if;
  return null;
end;
$$;
revoke all on function private.audit_presentation_slot_holder() from public, anon, authenticated;
create trigger presentation_slots_audit_holder after update of officer_id on public.presentation_slots
  for each row when (old.officer_id is distinct from new.officer_id) execute function private.audit_presentation_slot_holder();

-- Run before the signup FK is checked so assigned slots are released and the
-- holder audit can record the precise reason in the same transaction.
create function private.release_presenter_slots_on_signup_delete() returns trigger
language plpgsql security definer set search_path = '' as $$
declare prior_reason text:=pg_catalog.current_setting('cappy.presentation_release_reason',true);
begin
  perform pg_catalog.set_config('cappy.presentation_release_reason','signup_removed',true);
  update public.presentation_slots set officer_id=null
    where event_id=old.event_id and officer_id=old.officer_id;
  perform pg_catalog.set_config('cappy.presentation_release_reason',coalesce(prior_reason,''),true);
  return old;
end;
$$;
revoke all on function private.release_presenter_slots_on_signup_delete() from public,anon,authenticated;
create trigger event_officers_release_presenter_slots before delete on public.event_officers
  for each row execute function private.release_presenter_slots_on_signup_delete();

create function private.audit_presentation_slot_record() returns trigger
language plpgsql security definer set search_path = '' as $$
declare actor_id bigint := private.current_active_officer_id();
begin
  if tg_op='INSERT' then
    perform private.write_audit_log('presentation.slot_added','event',new.event_id::text,
      pg_catalog.jsonb_build_object('slot_id',new.id,'position',new.position,'actor_id',actor_id));
    return new;
  end if;
  perform private.write_audit_log('presentation.slot_removed','event',old.event_id::text,
    pg_catalog.jsonb_build_object('slot_id',old.id,'position',old.position,'actor_id',actor_id));
  return old;
end;
$$;
revoke all on function private.audit_presentation_slot_record() from public, anon, authenticated;
create trigger presentation_slots_audit_insert after insert on public.presentation_slots
  for each row execute function private.audit_presentation_slot_record();
create trigger presentation_slots_audit_delete before delete on public.presentation_slots
  for each row execute function private.audit_presentation_slot_record();

create function private.release_inactive_officer_presenter_slots() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  update public.presentation_slots s set officer_id=null from public.events e
    where s.officer_id=new.id and e.id=s.event_id and e.starts_at>pg_catalog.now();
  return null;
end;
$$;
revoke all on function private.release_inactive_officer_presenter_slots() from public, anon, authenticated;
create trigger officers_release_presenter_slots after update of status on public.officers
  for each row when (old.status='active' and new.status<>'active')
  execute function private.release_inactive_officer_presenter_slots();

create function private.add_presenter_slot(p_event_id bigint) returns bigint
language plpgsql security definer set search_path = '' as $$
declare current_event public.events; new_id bigint; next_position integer;
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  select * into current_event from public.events where id=p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if not private.can_manage_event(p_event_id) then raise exception 'Event outside branch scope'; end if;
  if not private.is_session_event_type(current_event.event_type_id) then raise exception 'Presenter slots are only allowed for Session Events'; end if;
  if not private.presenter_slots_open(current_event) then raise exception 'Presenter slots are closed for this event'; end if;
  select coalesce(max(position),0)+1 into next_position from public.presentation_slots where event_id=p_event_id;
  insert into public.presentation_slots(event_id,position) values(p_event_id,next_position) returning id into new_id;
  return new_id;
end;
$$;

create function private.reorder_presenter_slots(p_event_id bigint,p_slot_ids bigint[]) returns void
language plpgsql security definer set search_path = '' as $$
declare current_event public.events; slot_id bigint; current_ids bigint[];
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  select * into current_event from public.events where id=p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if not private.can_manage_event(p_event_id) then raise exception 'Event outside branch scope'; end if;
  if not private.is_session_event_type(current_event.event_type_id) then raise exception 'Presenter slots are only allowed for Session Events'; end if;
  if not private.presenter_slots_open(current_event) then raise exception 'Presenter slots are closed for this event'; end if;
  if p_slot_ids is null or cardinality(p_slot_ids)<>(select count(*) from public.presentation_slots where event_id=p_event_id)
    or cardinality(p_slot_ids)<>(select count(distinct x) from unnest(p_slot_ids) x) then
    raise exception 'Reorder must include every presenter slot exactly once'; end if;
  if exists(select 1 from unnest(p_slot_ids) x left join public.presentation_slots s on s.id=x and s.event_id=p_event_id where s.id is null) then
    raise exception 'Reorder must include every presenter slot exactly once'; end if;
  select coalesce(array_agg(id order by position),'{}'::bigint[]) into current_ids
    from public.presentation_slots where event_id=p_event_id;
  if current_ids is not distinct from p_slot_ids then return; end if;
  for slot_id in select x from unnest(p_slot_ids) with ordinality as slots(x,n) order by n loop
    update public.presentation_slots set position=(select ordinality::integer from unnest(p_slot_ids) with ordinality u(id,ordinality) where u.id=slot_id)
      where id=slot_id;
  end loop;
  perform private.write_audit_log('presentation.slots_reordered','event',p_event_id::text,
    pg_catalog.jsonb_build_object('slot_ids',p_slot_ids,'actor_id',private.current_active_officer_id()));
end;
$$;

create function private.remove_presenter_slot(p_slot_id bigint) returns void
language plpgsql security definer set search_path = '' as $$
declare slot public.presentation_slots; current_event public.events;
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  select * into slot from public.presentation_slots where id=p_slot_id;
  if not found then raise exception 'Presenter slot not found'; end if;
  select * into current_event from public.events where id=slot.event_id for update;
  select * into slot from public.presentation_slots where id=p_slot_id;
  if not private.can_manage_event(slot.event_id) then raise exception 'Event outside branch scope'; end if;
  if not private.presenter_slots_open(current_event) then raise exception 'Presenter slots are closed for this event'; end if;
  if slot.officer_id is not null then raise exception 'Remove the presenter before removing their slot'; end if;
  delete from public.presentation_slots where id=p_slot_id;
  update public.presentation_slots set position=position-1 where event_id=slot.event_id and position>slot.position;
end;
$$;

create function private.change_presenter_slot(p_slot_id bigint,p_officer_id bigint,p_release boolean default false)
returns void language plpgsql security definer set search_path = '' as $$
declare current_event public.events; slot public.presentation_slots; actor_id bigint:=private.current_active_officer_id();
begin
  if actor_id is null then raise exception 'Unauthorized'; end if;
  select * into slot from public.presentation_slots where id=p_slot_id;
  if not found then raise exception 'Presenter slot not found'; end if;
  select * into current_event from public.events where id=slot.event_id for update;
  select * into slot from public.presentation_slots where id=p_slot_id;
  if not private.is_session_event_type(current_event.event_type_id) then raise exception 'Presenter slots are only allowed for Session Events'; end if;
  if not private.presenter_slots_open(current_event) then raise exception 'Presenter slots are closed for this event'; end if;
  if p_officer_id is distinct from actor_id and not private.can_manage_event(slot.event_id) then raise exception 'Cannot manage another officer presenter slot for this event'; end if;
  if coalesce(p_release,false) then
    update public.presentation_slots set officer_id=null where id=p_slot_id and officer_id=p_officer_id;
    return;
  end if;
  if slot.officer_id=p_officer_id then return; end if;
  if slot.officer_id is not null then raise exception 'Presenter slot is already taken'; end if;
  perform 1 from public.officers where id=p_officer_id and status='active' for share;
  if not found then raise exception 'Target officer is not active'; end if;
  perform private.change_event_signup(slot.event_id,p_officer_id,false);
  if not exists(select 1 from public.event_officers where event_id=slot.event_id and officer_id=p_officer_id) then
    raise exception 'Event is full, so this officer cannot take a presenter slot'; end if;
  update public.presentation_slots set officer_id=p_officer_id where id=p_slot_id;
end;
$$;

create function private.update_presenter_slot_details(p_slot_id bigint,p_title text,p_url text,p_difficulty text,p_notes text)
returns void language plpgsql security definer set search_path = '' as $$
declare current_event public.events; slot public.presentation_slots;
  new_title text:=nullif(pg_catalog.btrim(p_title),''); new_url text:=nullif(pg_catalog.btrim(p_url),'');
  new_notes text:=nullif(pg_catalog.btrim(p_notes),'');
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  select * into slot from public.presentation_slots where id=p_slot_id;
  if not found then raise exception 'Presenter slot not found'; end if;
  select * into current_event from public.events where id=slot.event_id for update;
  select * into slot from public.presentation_slots where id=p_slot_id;
  if not private.can_manage_event(slot.event_id) then raise exception 'Event outside branch scope'; end if;
  if not private.presenter_slots_open(current_event) then raise exception 'Presenter slots are closed for this event'; end if;
  if new_url is not null and new_url !~* '^https?://[^[:space:]]+$' then raise exception 'Resource link must be an HTTP(S) URL'; end if;
  if length(new_title)>200 or length(new_notes)>2000 or length(p_difficulty)>100 then raise exception 'Presenter slot details are too long'; end if;
  if (new_title,new_url,p_difficulty,new_notes) is distinct from (slot.presentation_title,slot.resource_url,slot.difficulty,slot.prep_notes) then
    update public.presentation_slots set presentation_title=new_title,resource_url=new_url,difficulty=p_difficulty,prep_notes=new_notes where id=p_slot_id;
    perform private.write_audit_log('presentation.details_updated','event',slot.event_id::text,
      pg_catalog.jsonb_build_object('slot_id',slot.id,'position',slot.position,'before',
        pg_catalog.jsonb_build_object('presentation_title',slot.presentation_title,'resource_url',slot.resource_url,'difficulty',slot.difficulty,'prep_notes',slot.prep_notes),
        'after',pg_catalog.jsonb_build_object('presentation_title',new_title,'resource_url',new_url,'difficulty',p_difficulty,'prep_notes',new_notes)));
  end if;
end;
$$;

