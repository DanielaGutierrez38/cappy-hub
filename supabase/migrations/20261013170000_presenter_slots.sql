-- Presenter slots let Officers volunteer to present one problem difficulty at
-- an Event. A slot with no officer_id is open; there is no stored status.
create table public.presentation_slots (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete restrict,
  difficulty text not null check (difficulty in ('easy','medium','hard')),
  officer_id bigint references public.officers(id) on delete restrict,
  problem_title text check (problem_title is null
    or length(pg_catalog.btrim(problem_title)) between 1 and 200),
  problem_url text check (problem_url is null
    or problem_url ~* '^https?://[^[:space:]]+$'),
  prep_notes text check (prep_notes is null
    or length(pg_catalog.btrim(prep_notes)) between 1 and 2000),
  created_at timestamptz not null default pg_catalog.now(),
  constraint presentation_slots_event_difficulty_key unique (event_id, difficulty),
  -- A presenter must be signed up for the Event. Removing the signup, by any
  -- path, reopens the slot instead of blocking the removal.
  constraint presentation_slots_presenter_signup_fkey
    foreign key (event_id, officer_id)
    references public.event_officers(event_id, officer_id)
    on delete set null (officer_id)
);
-- An Officer presents at most one difficulty per Event.
create unique index presentation_slots_one_per_officer_uidx
  on public.presentation_slots(event_id, officer_id) where officer_id is not null;
create index presentation_slots_officer_id_idx
  on public.presentation_slots(officer_id) where officer_id is not null;

alter table public.presentation_slots enable row level security;
revoke all on public.presentation_slots from public, anon, authenticated;
grant select on public.presentation_slots to authenticated;
create policy "Approved officers read presenter slots" on public.presentation_slots
  for select to authenticated
  using ((select private.current_active_officer_id()) is not null);

-- Slots close when the Event starts; Event signups stay open until it ends.
create function private.presenter_slots_open(p_event public.events) returns boolean
language sql stable set search_path = '' as $$
  select p_event.deleted_at is null and p_event.status <> 'cancelled'
    and p_event.participation_points_per_hour_at_end is null
    and p_event.starts_at > pg_catalog.now()
$$;
revoke all on function private.presenter_slots_open(public.events)
  from public, anon, authenticated;

-- Every change of slot holder is audited here, whether it came from the RPC
-- below or from the signup foreign key reopening the slot.
create function private.audit_presentation_slot_holder() returns trigger
language plpgsql security definer set search_path = '' as $$
declare actor_id bigint := private.current_active_officer_id();
begin
  if old.officer_id is not null then
    perform private.write_audit_log(
      case when old.officer_id = actor_id then 'presentation.released'
        else 'presentation.unassigned' end,
      'event', old.event_id::text,
      pg_catalog.jsonb_build_object('slot_id', old.id, 'difficulty', old.difficulty,
        'officer_id', old.officer_id, 'actor_id', actor_id,
        'reason', case when exists(select 1 from public.event_officers
            where event_id = old.event_id and officer_id = old.officer_id)
          then 'requested' else 'signup_removed' end));
  end if;
  if new.officer_id is not null then
    perform private.write_audit_log(
      case when new.officer_id = actor_id then 'presentation.claimed'
        else 'presentation.assigned' end,
      'event', new.event_id::text,
      pg_catalog.jsonb_build_object('slot_id', new.id, 'difficulty', new.difficulty,
        'officer_id', new.officer_id, 'actor_id', actor_id));
  end if;
  return null;
end;
$$;
revoke all on function private.audit_presentation_slot_holder()
  from public, anon, authenticated;

create trigger presentation_slots_audit_holder
  after update of officer_id on public.presentation_slots
  for each row when (old.officer_id is distinct from new.officer_id)
  execute function private.audit_presentation_slot_holder();

create function private.set_presenter_slots(p_event_id bigint, p_difficulties text[])
returns void language plpgsql security definer set search_path = '' as $$
declare
  current_event public.events;
  wanted text[] := coalesce(p_difficulties, '{}'::text[]);
  previous text[];
  saved text[];
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  select * into current_event from public.events where id = p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if not private.can_manage_event(p_event_id) then
    raise exception 'Event outside branch scope'; end if;
  if not private.presenter_slots_open(current_event) then
    raise exception 'Presenter slots are closed for this event'; end if;
  if exists(select 1 from pg_catalog.unnest(wanted) d
      where d is null or d not in ('easy','medium','hard')) then
    raise exception 'Invalid presenter slot difficulty'; end if;
  if exists(select 1 from public.presentation_slots where event_id = p_event_id
      and officer_id is not null and difficulty <> all(wanted)) then
    raise exception 'Remove the presenter before removing their slot'; end if;

  select coalesce(pg_catalog.array_agg(difficulty order by difficulty), '{}'::text[])
    into previous from public.presentation_slots where event_id = p_event_id;
  delete from public.presentation_slots
    where event_id = p_event_id and difficulty <> all(wanted);
  insert into public.presentation_slots(event_id, difficulty)
    select distinct p_event_id, d from pg_catalog.unnest(wanted) d
    on conflict (event_id, difficulty) do nothing;
  select coalesce(pg_catalog.array_agg(difficulty order by difficulty), '{}'::text[])
    into saved from public.presentation_slots where event_id = p_event_id;
  if saved is distinct from previous then
    perform private.write_audit_log('presentation.slots_updated', 'event', p_event_id::text,
      pg_catalog.jsonb_build_object('name', current_event.name,
        'previous_difficulties', previous, 'difficulties', saved));
  end if;
end;
$$;

create function private.change_presenter_slot(
  p_event_id bigint, p_difficulty text, p_officer_id bigint, p_release boolean
) returns void language plpgsql security definer set search_path = '' as $$
declare
  current_event public.events;
  slot public.presentation_slots;
  actor_id bigint := private.current_active_officer_id();
begin
  if actor_id is null then raise exception 'Unauthorized'; end if;
  -- The same Event row lock as signups, so claims, sign-outs and cancellation
  -- of one Event are serialized.
  select * into current_event from public.events where id = p_event_id for update;
  if not found then raise exception 'Event not found'; end if;
  if not private.presenter_slots_open(current_event) then
    raise exception 'Presenter slots are closed for this event'; end if;
  if p_officer_id is distinct from actor_id and not private.can_manage_event(p_event_id) then
    raise exception 'Cannot manage another officer presenter slot for this event'; end if;
  select * into slot from public.presentation_slots
    where event_id = p_event_id and difficulty = p_difficulty;
  if not found then raise exception 'Presenter slot not found'; end if;

  if coalesce(p_release, false) then
    update public.presentation_slots set officer_id = null
      where id = slot.id and officer_id = p_officer_id;
    return;
  end if;
  if slot.officer_id = p_officer_id then return; end if;
  if slot.officer_id is not null then
    raise exception 'Presenter slot is already taken'; end if;
  if exists(select 1 from public.presentation_slots
      where event_id = p_event_id and officer_id = p_officer_id) then
    raise exception 'Officer already has a presenter slot for this event'; end if;
  -- Presenting counts as attending: reuse the audited signup path, which also
  -- rejects inactive Officers.
  perform private.change_event_signup(p_event_id, p_officer_id, false);
  update public.presentation_slots set officer_id = p_officer_id where id = slot.id;
end;
$$;

create function private.update_presenter_slot_details(
  p_slot_id bigint, p_problem_title text, p_problem_url text, p_prep_notes text
) returns void language plpgsql security definer set search_path = '' as $$
declare
  current_event public.events;
  slot public.presentation_slots;
  slot_event_id bigint;
  new_title text := nullif(pg_catalog.btrim(p_problem_title), '');
  new_url text := nullif(pg_catalog.btrim(p_problem_url), '');
  new_notes text := nullif(pg_catalog.btrim(p_prep_notes), '');
begin
  if private.current_active_officer_id() is null then raise exception 'Unauthorized'; end if;
  select event_id into slot_event_id from public.presentation_slots where id = p_slot_id;
  if not found then raise exception 'Presenter slot not found'; end if;
  select * into current_event from public.events where id = slot_event_id for update;
  select * into slot from public.presentation_slots where id = p_slot_id;
  if not found then raise exception 'Presenter slot not found'; end if;
  if not private.can_manage_event(slot.event_id) then
    raise exception 'Event outside branch scope'; end if;
  if not private.presenter_slots_open(current_event) then
    raise exception 'Presenter slots are closed for this event'; end if;
  if new_url is not null and new_url !~* '^https?://[^[:space:]]+$' then
    raise exception 'Problem link must be an HTTP(S) URL'; end if;
  if length(new_title) > 200 or length(new_notes) > 2000 then
    raise exception 'Presenter slot details are too long'; end if;

  if (new_title, new_url, new_notes) is distinct from
      (slot.problem_title, slot.problem_url, slot.prep_notes) then
    update public.presentation_slots
      set problem_title = new_title, problem_url = new_url, prep_notes = new_notes
      where id = p_slot_id;
    perform private.write_audit_log('presentation.details_updated', 'event', slot.event_id::text,
      pg_catalog.jsonb_build_object('slot_id', slot.id, 'difficulty', slot.difficulty,
        'before', pg_catalog.jsonb_build_object('problem_title', slot.problem_title,
          'problem_url', slot.problem_url, 'prep_notes', slot.prep_notes),
        'after', pg_catalog.jsonb_build_object('problem_title', new_title,
          'problem_url', new_url, 'prep_notes', new_notes)));
  end if;
end;
$$;

create function public.set_presenter_slots(p_event_id bigint, p_difficulties text[])
returns void language sql security invoker set search_path = '' as $$
  select private.set_presenter_slots(p_event_id, p_difficulties)
$$;
create function public.change_presenter_slot(
  p_event_id bigint, p_difficulty text, p_officer_id bigint, p_release boolean default false
) returns void language sql security invoker set search_path = '' as $$
  select private.change_presenter_slot(p_event_id, p_difficulty, p_officer_id, p_release)
$$;
create function public.update_presenter_slot_details(
  p_slot_id bigint, p_problem_title text, p_problem_url text, p_prep_notes text
) returns void language sql security invoker set search_path = '' as $$
  select private.update_presenter_slot_details(
    p_slot_id, p_problem_title, p_problem_url, p_prep_notes)
$$;

